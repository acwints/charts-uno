#!/usr/bin/env python3
"""Build the synced iOS bundle with Xcode-generated simulator entitlements."""
import os
from pathlib import Path
import platform
import subprocess

root = Path(__file__).resolve().parents[1]
output = Path(os.environ.get("CHARTSUNO_SIMULATOR_BUILD_DIR", str(root / "packages/mobile/build/simulator"))).resolve()
command = [
    "xcodebuild", "-project", "packages/mobile/ios/App/App.xcodeproj",
    "-scheme", "App", "-configuration", "Debug",
    "-destination", "generic/platform=iOS Simulator",
    "-derivedDataPath", str(output),
    "CODE_SIGN_IDENTITY=-", "CODE_SIGNING_ALLOWED=YES",
    "ONLY_ACTIVE_ARCH=YES", f"ARCHS={platform.machine()}", "build",
]
# Keep simulator entitlements generated by Xcode. Disabling signing breaks
# Keychain access; manually signing afterward omits simulator-specific metadata.
wrapper = Path.home() / ".local/bin/heavy-build"
if wrapper.exists():
    command.insert(0, str(wrapper))
subprocess.run(command, cwd=root, check=True)
print(f"Simulator app: {output / 'Build/Products/Debug-iphonesimulator/App.app'}")
